/** MATLAB helper that serializes SISO LTI model arrays to the variant JSON importer. */
export function matlabWorkspaceArrayExportScript(): string {
  return [
    "function exportSisoToolsWorkspaceModels(G, H, fileName, sampleCount, seed)",
    "% Exporta arrays SISO tf/zpk/ss/frd do Workspace para importar como variantes no LasecSimul.",
    "% Tambem amostra um modelo incerto SISO uss/ufrd com usample (Robust Control Toolbox).",
    "% Uso: exportSisoToolsWorkspaceModels(G, H, 'modelos-siso.json', 20, 1)",
    "% G e H podem ser arrays LTI homogeneos ou cell arrays de modelos SISO; H pode ser [].",
    "if nargin < 2, H = []; end",
    "if nargin < 3 || isempty(fileName), fileName = 'modelos-siso.json'; end",
    "if nargin < 4 || isempty(sampleCount), sampleCount = 20; end",
    "if nargin < 5 || isempty(seed), seed = 1; end",
    "gUncertain = isa(G, 'uss') || isa(G, 'ufrd');",
    "hUncertain = isa(H, 'uss') || isa(H, 'ufrd');",
    "if gUncertain && hUncertain, error('Amostre G e H juntos fora deste auxiliar para preservar parametros incertos compartilhados; passe arrays numericos alinhados.'); end",
    "if gUncertain || hUncertain",
    "    if ~isscalar(sampleCount) || sampleCount < 2 || sampleCount > 100 || sampleCount ~= floor(sampleCount), error('sampleCount deve ser inteiro de 2 a 100.'); end",
    "    if ~isscalar(seed) || seed < 0 || seed > 2^32-1 || seed ~= floor(seed), error('seed deve ser inteiro de 0 a 2^32-1.'); end",
    "    previousRng = rng; rngCleanup = onCleanup(@() rng(previousRng));",
    "    rng(seed, 'twister');",
    "    if gUncertain, if ~issiso(G), error('G incerto deve ser SISO.'); end; G = usample(G, sampleCount); end",
    "    if hUncertain, if ~issiso(H), error('H incerto deve ser SISO.'); end; H = usample(H, sampleCount); end",
    "end",
    "plants = localModels(G, 'G');",
    "if numel(plants) < 1 || numel(plants) > 100, error('G deve conter de 1 a 100 modelos SISO.'); end",
    "sensors = {};",
    "if ~isempty(H), sensors = localModels(H, 'H'); end",
    "if ~isempty(sensors) && numel(sensors) ~= 1 && numel(sensors) ~= numel(plants)",
    "    error('H deve ser escalar ou ter o mesmo numero de modelos que G.');",
    "end",
    "if ~isempty(sensors) && ~isequal(localDomain(sensors{1}), localDomain(plants{1})), error('G e H devem usar o mesmo dominio.'); end",
    "if ~isempty(sensors) && strcmp(localDomain(plants{1}), 'discrete') && abs(localSampleTime(sensors{1}) - localSampleTime(plants{1})) > 1e-12 * max(1, localSampleTime(plants{1})), error('G e H devem usar o mesmo sample time.'); end",
    "models = cell(1, numel(plants));",
    "for k = 1:numel(plants)",
    "    sys = plants{k};",
    "    [num, den, stateSpace, frdData, approximation] = localSerialize(sys, sprintf('G(%d)', k));",
    "    entry = struct('name', sprintf('G(%d)', k), 'plant', struct('num', num, 'den', den), ...",
    "        'domain', localDomain(sys), 'sampleTime', localSampleTime(sys));",
    "    if ~isempty(stateSpace), entry.stateSpace = stateSpace; end",
    "    if ~isempty(frdData), entry.plantFrd = frdData; entry.approximation = approximation; end",
    "    if ~isempty(sensors)",
    "        sensor = sensors{min(k, numel(sensors))};",
    "        [sensorNum, sensorDen, ~, sensorFrd, sensorApproximation] = localSerialize(sensor, sprintf('H(%d)', min(k, numel(sensors))));",
    "        entry.sensor = struct('num', sensorNum, 'den', sensorDen);",
    "        if ~isempty(sensorFrd), entry.sensorFrd = sensorFrd; entry.sensorApproximation = sensorApproximation; end",
    "    end",
    "    models{k} = entry;",
    "end",
    "payload = struct('models', {models});",
    "json = jsonencode(payload);",
    "fid = fopen(fileName, 'w', 'n', 'UTF-8');",
    "if fid < 0, error('Nao foi possivel criar %s.', fileName); end",
    "cleanup = onCleanup(@() fclose(fid));",
    "fwrite(fid, json, 'char');",
    "fprintf('Exportados %d modelos SISO para %s\\n', numel(plants), fileName);",
    "end",
    "",
    "function models = localModels(value, label)",
    "if iscell(value)",
    "    models = value(:).';",
    "else",
    "    models = cell(1, numel(value));",
    "    for i = 1:numel(value), models{i} = value(i); end",
    "end",
    "for i = 1:numel(models)",
    "    sys = models{i};",
    "    if ~(isa(sys, 'tf') || isa(sys, 'zpk') || isa(sys, 'ss') || isa(sys, 'frd')) || ~issiso(sys)",
    "        error('%s{%d} deve ser um modelo SISO tf, zpk, ss ou frd.', label, i);",
    "    end",
    "    if i > 1 && ~isequal(localDomain(sys), localDomain(models{1}))",
    "        error('%s nao pode misturar modelos continuos e discretos.', label);",
    "    end",
    "    if i > 1 && strcmp(localDomain(sys), 'discrete') && abs(localSampleTime(sys) - localSampleTime(models{1})) > 1e-12 * max(1, localSampleTime(sys))",
    "        error('%s nao pode misturar sample times diferentes.', label);",
    "    end",
    "end",
    "end",
    "",
    "function domain = localDomain(sys)",
    "if sys.Ts == 0, domain = 'continuous'; else, domain = 'discrete'; end",
    "end",
    "",
    "function sampleTime = localSampleTime(sys)",
    "sampleTime = sys.Ts;",
    "if sampleTime == 0, sampleTime = 0.1; end",
    "end",
    "",
    "function [num, den, stateSpace, frdData, approximation] = localSerialize(sys, label)",
    "stateSpace = []; frdData = []; approximation = '';",
    "if isa(sys, 'frd')",
    "    measured = chgFreqUnit(sys, 'rad/s');",
    "    frequency = measured.Frequency(:).';",
    "    response = squeeze(measured.ResponseData); response = response(:).';",
    "    keep = isfinite(frequency) & frequency > 0 & isfinite(real(response)) & isfinite(imag(response));",
    "    frequency = frequency(keep); response = response(keep);",
    "    [frequency, order] = sort(frequency); response = response(order);",
    "    [frequency, uniqueIndex] = unique(frequency, 'stable'); response = response(uniqueIndex);",
    "    if numel(frequency) < 4, error('%s precisa ter ao menos quatro frequencias positivas validas.', label); end",
    "    if sys.Ts > 0 && frequency(end) > pi / sys.Ts * (1 + 1e-12), error('%s excede Nyquist.', label); end",
    "    pairs = arrayfun(@(i) struct('re', real(response(i)), 'im', imag(response(i))), 1:numel(response));",
    "    frdData = struct('frequencyRadPerSecond', frequency, 'response', pairs, 'sourceUnit', char(sys.FrequencyUnit));",
    "    fitOrder = min(6, max(1, floor((numel(frequency) - 1) / 2)));",
    "    if exist('fitfrd', 'file') == 2",
    "        try, fitted = fitfrd(measured, fitOrder); if ~isstable(fitted), fitted = []; end; if ~isempty(fitted), approximation = 'fitfrd'; end",
    "        catch, fitted = []; end",
    "    else, fitted = []; end",
    "    if isempty(fitted)",
    "        fitted = tf(real(response(1))); approximation = 'ganho-estatico-no-primeiro-ponto';",
    "    end",
    "    [num, den] = tfdata(tf(fitted), 'v');",
    "else",
    "    [num, den] = tfdata(tf(sys), 'v');",
    "    if isa(sys, 'ss')",
    "        [A, B, C, D] = ssdata(sys);",
    "        stateSpace = struct('A', A, 'B', B(:).', 'C', C(:).', 'D', D(1));",
    "    end",
    "end",
    "num = num(:).'; den = den(:).';",
    "scale = max([1 abs(num) abs(den)]);",
    "if max(abs(imag(num))) > 1e-9 * scale || max(abs(imag(den))) > 1e-9 * scale, error('%s tem coeficientes complexos; o importador aceita somente modelos reais.', label); end",
    "num = real(num); den = real(den);",
    "if isempty(num) || isempty(den) || any(~isfinite(num)) || any(~isfinite(den)) || numel(num) > numel(den)",
    "    error('%s nao produziu uma aproximacao racional propria e finita.', label);",
    "end",
    "end",
    "",
  ].join("\n");
}
